import sv.edu.ues.occ.ingenieria.ppi115_2026_salud.galenosv.control.*;
import sv.edu.ues.occ.ingenieria.ppi115_2026_salud.galenosv.entity.*;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.Mockito.*;
import sv.edu.ues.occ.ingenieria.ppi115_2026_salud.galenosv.boundary.jsf.RolModel;

@ExtendWith(MockitoExtension.class)
class RolModelTest {

    @Mock
    private RolService rolServiceMock;

    private RolModel rolModel;

    private UUID sampleId;
    private Rol sampleRol;

    @BeforeEach
    void setUp() {
        sv.edu.ues.occ.ingenieria.ppi115_2026_salud.galenosv.jsf.ModelTestSupport.crearModelo(this, RolModel.class, "rolModel");
        sampleId = UUID.randomUUID();
        sampleRol = new Rol();
        sampleRol.setIdRol(sampleId);
        sampleRol.setNombre("Doctor");
    }

    // ==========================================
    // PRUEBAS PARA getDAO
    // ==========================================

    @Test
    @DisplayName("getDAO - Éxito (Retorna el servicio inyectado)")
    void getDAO_Success() {
        assertSame(rolServiceMock, rolModel.getDAO());
    }

    // ==========================================
    // PRUEBAS PARA instanciarRegistro
    // ==========================================

    @Test
    @DisplayName("instanciarRegistro - Éxito (Retorna una instancia nueva y vacía cada vez)")
    void instanciarRegistro_Success() {
        Rol primero = rolModel.instanciarRegistro();
        Rol segundo = rolModel.instanciarRegistro();

        assertNotNull(primero);
        assertNull(primero.getIdRol());
        assertNotSame(primero, segundo);
    }

    // ==========================================
    // PRUEBAS PARA getRegistroById
    // ==========================================

    @Test
    @DisplayName("getRegistroById - Éxito (Retorna el registro que encuentra el servicio)")
    void getRegistroById_Success() {
        when(rolServiceMock.buscar(sampleId)).thenReturn(sampleRol);

        Rol resultado = rolModel.getRegistroById(sampleId.toString());

        assertSame(sampleRol, resultado);
        verify(rolServiceMock, times(1)).buscar(sampleId);
    }

    @Test
    @DisplayName("getRegistroById - Fallos (ID con formato inválido o registro inexistente retornan null)")
    void getRegistroById_Failures() {
        UUID idInexistente = UUID.randomUUID();
        when(rolServiceMock.buscar(idInexistente)).thenReturn(null);

        assertNull(rolModel.getRegistroById("no-es-un-uuid"));
        assertNull(rolModel.getRegistroById(idInexistente.toString()));

        // Solo el ID válido llegó al servicio
        verify(rolServiceMock, times(1)).buscar(any());
    }

    // ==========================================
    // PRUEBAS PARA getIdByRegistro
    // ==========================================

    @Test
    @DisplayName("getIdByRegistro - Éxito (Retorna el id del registro)")
    void getIdByRegistro_Success() {
        assertEquals(sampleId, rolModel.getIdByRegistro(sampleRol));
    }

    @Test
    @DisplayName("getIdByRegistro - Fallos (Registro nulo retorna null)")
    void getIdByRegistro_Failures() {
        assertNull(rolModel.getIdByRegistro(null));
    }

    // ==========================================
    // PRUEBAS PARA getLazyModel
    // ==========================================

    @Test
    @DisplayName("getLazyModel - Éxito (Modelo perezoso conectado a este Model)")
    void getLazyModel_Success() {
        when(rolServiceMock.contar()).thenReturn(3);

        assertNotNull(rolModel.getLazyModel());
        assertEquals(3, rolModel.getLazyModel().count(Collections.emptyMap()));
    }
}
